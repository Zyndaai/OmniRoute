// Dumps the logical SQLite schema that the app builds on a fresh database
// (core init + every migration) into a SQL file. Used as the reference for the
// hand-translated PostgreSQL baseline.
//
// Usage: node --import tsx/esm scripts/db/dump-sqlite-schema.mjs [outputPath]
//
// DATA_DIR is pointed at a freshly created temp directory BEFORE the app modules are
// imported (core.ts resolves DATA_DIR at import time), and that directory is deleted at
// the end. The real data directory is never opened.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const outPath = process.argv[2]
  ? path.resolve(process.argv[2])
  : path.join(repoRoot, "src", "lib", "db", "backends", "postgres", "sqlite-schema-snapshot.sql");

const tempDataDir = fs.mkdtempSync(path.join(os.tmpdir(), "omniroute-schema-dump-"));
process.env.DATA_DIR = tempDataDir;
process.env.APP_LOG_TO_FILE = "false";

const SCHEMA_QUERY = `
  SELECT type, name, tbl_name, sql FROM sqlite_master
  WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
  ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'trigger' THEN 2 ELSE 3 END,
           tbl_name, name
`;

// Shadow tables of FTS5 (`<vt>_data`, `_idx`, `_docsize`, `_config`, `_content`) and of
// sqlite-vec vec0 (`<vt>_chunks`, `_rowids`, `_vector_chunksNN`).
const SHADOW_SUFFIX = /_(data|idx|docsize|config|content|chunks|rowids|vector_chunks\d+)$/;

function statementBody(sql) {
  return sql.trim().replace(/;+\s*$/, "");
}

function buildDump({ entries, header, sqliteOnlyNames }) {
  const lines = [...header, ""];
  for (const entry of entries) {
    lines.push(`-- ${entry.type} ${entry.name} on ${entry.tbl_name}`);
    if (sqliteOnlyNames.has(entry.name)) lines.push("-- SQLITE-ONLY");
    lines.push(`${statementBody(entry.sql)};`);
    lines.push("");
  }
  return `${lines.join("\n")}\n`;
}

async function main() {
  let core;
  try {
    core = await import("../../src/lib/db/core.ts");
    const { supportsFts5 } = await import("../../src/lib/db/migrationRunner.ts");
    // getDbInstance() runs the whole first-boot init. ensureDbInitialized() is not used:
    // its sync probe creates the empty file before init, so the migration runner treats
    // a fresh database as an existing one and aborts the mass-migration safety check.
    const db = core.getDbInstance();

    const entries = db.prepare(SCHEMA_QUERY).all();
    const virtualTables = entries.filter(
      (entry) => entry.type === "table" && /^CREATE VIRTUAL TABLE/i.test(statementBody(entry.sql))
    );
    const sqliteOnlyNames = new Set(virtualTables.map((entry) => entry.name));
    for (const entry of entries) {
      if (entry.type !== "table" || sqliteOnlyNames.has(entry.name)) continue;
      const shadowOf = virtualTables.some(
        (vt) => entry.name.startsWith(`${vt.name}_`) && SHADOW_SUFFIX.test(entry.name)
      );
      if (shadowOf) sqliteOnlyNames.add(entry.name);
    }

    const migrationRows = db.prepare("SELECT version FROM _omniroute_migrations").all();
    const numericVersions = migrationRows
      .map((row) => row.version)
      .filter((version) => /^\d+$/.test(version))
      .map(Number);
    const highestVersion = numericVersions.length > 0 ? String(Math.max(...numericVersions)).padStart(3, "0") : "none";

    const header = [
      "-- SQLite logical schema snapshot (reference for the PostgreSQL baseline).",
      "-- Generated by scripts/db/dump-sqlite-schema.mjs; do not hand-edit.",
      `-- Generated at: ${new Date().toISOString()}`,
      `-- Driver: ${db.driver}`,
      `-- FTS5 available: ${supportsFts5(db) ? "yes" : "no (FTS5 migrations were deferred; FTS tables absent)"}`,
      `-- Migration count (_omniroute_migrations rows): ${migrationRows.length}`,
      `-- Highest migration version: ${highestVersion}`,
      "-- Lines marked SQLITE-ONLY are virtual tables and their shadow tables; they have no direct PostgreSQL equivalent.",
    ];

    const dumpText = buildDump({ entries, header, sqliteOnlyNames });
    const counts = {
      tables: entries.filter((e) => e.type === "table").length,
      indexes: entries.filter((e) => e.type === "index").length,
      triggers: entries.filter((e) => e.type === "trigger").length,
      virtualTables: virtualTables.length,
      sqliteOnly: sqliteOnlyNames.size,
      migrations: migrationRows.length,
      highestVersion,
    };
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    fs.writeFileSync(outPath, dumpText);
    console.log(`[dump-sqlite-schema] wrote ${outPath}`);
    console.log(`[dump-sqlite-schema] ${JSON.stringify(counts)}`);
  } finally {
    if (core) await core.shutdownDbInstance();
    fs.rmSync(tempDataDir, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 });
  }
}

main().then(
  () => process.exit(0),
  (error) => {
    console.error("[dump-sqlite-schema] failed:", error);
    process.exit(1);
  }
);
